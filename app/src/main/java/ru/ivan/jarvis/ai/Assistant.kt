package ru.ivan.jarvis.ai

import java.time.LocalDateTime
import java.time.format.DateTimeFormatter
import java.util.Locale

/**
 * Решает, когда звать ИИ, и разбирает его ответ.
 * Экономия токенов: короткий системный промпт, лимит ответа, без длинной истории,
 * ИИ вызывается только для вопросов и просьб, которые не поняли локальные разборщики.
 */
object Assistant {
    private val OPT = setOf(RegexOption.IGNORE_CASE)

    private val askAi = Regex(
        "^(как|что|чем|почему|зачем|сколько|где|когда|какой|какая|какое|какие|кто|можно ли|стоит ли|" +
            "посоветуй|помоги|расскажи|объясни|разбей|раздели|придумай|составь|подскажи|переведи|сформулируй|" +
            "напиши\\s+(текст|письмо|пост|ответ)|спроси|скажи|мне\\s+(лень|скучно|плохо|тяжело|грустно)|не\\s+могу|" +
            "с\\s+чего\\s+начать|я\\s+не\\s+знаю|я\\s+(устал|запутался|отвлекаюсь|прокрастинирую))(?![\\p{L}])",
        OPT,
    )

    /** Стоит ли отправлять фразу ИИ (а не сохранять как заметку). */
    fun shouldAsk(text: String): Boolean {
        val t = text.trim().replace(Regex("^(джарвис|jarvis)[\\s,.!]*", OPT), "")
        return t.endsWith("?") || askAi.containsMatchIn(t)
    }

    fun systemPrompt(now: LocalDateTime = LocalDateTime.now(), facts: String = "", about: String = ""): String {
        val date = now.format(DateTimeFormatter.ofPattern("EEEE d MMMM, HH:mm", Locale("ru")))
        val me = buildString {
            if (about.isNotBlank()) append("\nО пользователе: ").append(about.take(400))
            if (facts.isNotBlank()) append("\nТы помнишь: ").append(facts)
        }
        return """Ты Джарвис — личный помощник Ивана. Иван твой шеф и главный: ты работаешь на него, его решение окончательное.
Обращайся к нему «шеф», на «вы», с уважением и без лести; коротко докладывай, как толковый помощник. Сейчас $date.$me
Отвечай по-русски, 1-3 коротких предложения, без markdown и эмодзи. Будь конкретен; если уместно, подскажи один следующий шаг.
ГЛАВНОЕ ПРАВИЛО: помогай только правильно, никакой самодеятельности. Делай ровно то, о чём просят; не выдумывай факты, цены, имена и сроки;
если не уверен или данных нет — честно скажи «не знаю» или переспроси одним коротким вопросом. Не предлагай действий, о которых не просили.
Правила СДВГ-коуча: давай одно действие за раз, а не список; первый шаг должен занимать 2-5 минут; называй время явно («через 40 минут встреча»);
не стыди и не дави, перенос дел — это нормально; если человек застрял, предложи правило 5 минут; хвали за сделанное.
Ты помогаешь руководителю автосервиса. Если фраза — дело или мысль, предложи записать её (CMD) — я сам спрошу «да».
Если нужно записать или напомнить, добавь отдельные строки:
CMD: напомни <когда> <что>
CMD: запиши <текст>
CMD: открой <приложение> | позвони <кому> | напиши смс <кому>: <текст> | будильник на <время> | таймер на <время>
CMD: сделай на телефоне <цель> — если нужно несколько действий в приложениях (найти в Озоне, включить в Ютубе, написать в Телеграм). Я сам буду нажимать на экране
CMD: найди <запрос> — если нужны свежие данные: цены, наличие, Драйв2, форумы, инструкции
CMD: запомни <факт> — если пользователь сообщил важное о себе, работе, людях
Когда пиши как человек: «завтра в 9», «через 20 минут».
Если просят разбить задачу или человек не знает, с чего начать большую задачу, добавь строку CMD: разбей <задача> — шаги я покажу по одному."""
    }

    /** Разбивка задачи на крошечные шаги (как Magic ToDo у Goblin Tools). */
    fun breakdownPrompt(facts: String = "", about: String = ""): String {
        val me = buildString {
            if (about.isNotBlank()) append("\nО пользователе: ").append(about.take(300))
            if (facts.isNotBlank()) append("\nИзвестно: ").append(facts.take(300))
        }
        return """Ты помогаешь человеку с СДВГ начать дело. Разбей задачу на 3-7 очень маленьких конкретных шагов.$me
Первый шаг — на 2-5 минут и совсем лёгкий (открыть, найти, достать). Каждый шаг начинается с глагола, до 12 слов, в конце в скобках примерное время.
Ответ — только нумерованный список, по шагу в строке, без вступления и без markdown."""
    }

    /** «Выгрузка из головы»: поток мыслей → отдельные дела. */
    fun dumpPrompt(now: LocalDateTime = LocalDateTime.now()): String {
        val date = now.format(DateTimeFormatter.ofPattern("EEEE d MMMM, HH:mm", Locale("ru")))
        return """Сейчас $date. Человек с СДВГ выгрузил из головы поток мыслей. Выдели из него все отдельные дела, идеи и покупки.
Каждое — отдельной строкой в одном из видов:
напомни <когда> <что> — если в тексте сказано время или день (пиши время как человек: «завтра в 9», «в пятницу»)
запиши <что> — если времени нет
Если сказано «срочно» или «важно», начни <что> со слова «срочно». Коротко, в повелительной форме, без пояснений и без нумерации."""
    }

    data class Parsed(val speech: String, val commands: List<String>)

    fun parse(answer: String): Parsed {
        val commands = mutableListOf<String>()
        val speech = mutableListOf<String>()
        answer.lines().map { it.trim() }.filter { it.isNotEmpty() }.forEach { line ->
            val m = Regex("^[*\\-\\s]*CMD\\s*:\\s*(.+)$", OPT).find(line)
            if (m != null) commands += m.groupValues[1].trim() else speech += line.replace(Regex("[*#_`]"), "")
        }
        return Parsed(speech.joinToString(" ").trim(), commands)
    }
}
